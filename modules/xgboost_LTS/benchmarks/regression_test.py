import time
import pandas as pd
import numpy as np
import logging
import sys
from pathlib import Path
from typing import Dict, Any

# Add project root to path
sys.path.append(str(Path(__file__).resolve().parent.parent.parent.parent))

from config import MODEL_FEATURES
from modules.xgboost_LTS.core.model import train_and_predict
from modules.random_forest.utils.features import add_price_derived_features, add_advanced_features
from modules.xgboost_LTS.core.labeling import apply_directional_labels

# Configure logging
logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger(__name__)


class BenchmarkSuite:
    def __init__(self, n_samples=10000):
        self.n_samples = n_samples
        self.df = self._generate_data()
        self.results = {}

    def _generate_data(self):
        logger.info(f"Generating {self.n_samples} dummy samples...")
        data = {
            "close": np.random.uniform(100, 200, self.n_samples),
            "open": np.random.uniform(100, 200, self.n_samples),
            "high": np.random.uniform(100, 200, self.n_samples),
            "low": np.random.uniform(100, 200, self.n_samples),
            "volume": np.random.uniform(1000, 10000, self.n_samples),
            # Mock other features if needed by adding random columns matching MODEL_FEATURES
        }
        # Ensure high/low consistency
        df = pd.DataFrame(data)
        df["high"] = df[["open", "close", "high"]].max(axis=1)
        df["low"] = df[["open", "close", "low"]].min(axis=1)

        # Add basic features to satisfy MODEL_FEATURES roughly if they aren't generated by feature engineering
        # But add_advanced_features should generate most.
        # Let's add dummy columns for any missing MODEL_FEATURES to prevent errors
        for feature in MODEL_FEATURES:
            if feature not in df.columns and feature not in ["Target"]:
                df[feature] = np.random.randn(self.n_samples)

        return df

    def benchmark_step(self, name: str, func, *args, **kwargs) -> Any:
        logger.info(f"Benchmarking step: {name}")
        start_time = time.perf_counter()
        result = func(*args, **kwargs)
        end_time = time.perf_counter()
        elapsed = end_time - start_time
        self.results[name] = elapsed
        logger.info(f"Step {name} finished in {elapsed:.4f}s")
        return result

    def run(self):
        # 1. Feature Engineering
        # We test add_advanced_features which calls add_price_derived_features internally
        df_features = self.benchmark_step("feature_engineering", add_advanced_features, self.df.copy())

        # 2. Labeling
        df_labeled = self.benchmark_step("labeling", apply_directional_labels, df_features.copy())

        # 3. Training
        # Use a subset for training to be faster in benchmark if needed, or full size
        # Ensure Target exists
        if "Target" not in df_labeled.columns:
            # Just in case labeling failed or logic changed
            logger.warning("Target column missing after labeling, adding dummy target for training benchmark")
            df_labeled["Target"] = np.random.randint(0, 3, len(df_labeled))

        # Drop NaNs before training as model expects clean data
        df_labeled = df_labeled.dropna()

        self.benchmark_step("training", train_and_predict, df_labeled, use_cache=False)

        return self.results

    def print_report(self):
        print("\n" + "=" * 30)
        print("BENCHMARK REPORT")
        print("=" * 30)
        print(f"Samples: {self.n_samples}")
        for task, duration in self.results.items():
            print(f"{task:<20}: {duration:.4f}s")
        print("=" * 30)


def run_regression_test():
    benchmark = BenchmarkSuite(n_samples=5000)
    results = benchmark.run()
    benchmark.print_report()

    # Define budget (example values, adjust based on baseline)
    budget = {
        "feature_engineering": 2.0,  # seconds
        "labeling": 1.0,
        "training": 15.0,
    }

    failures = []
    for task, limit in budget.items():
        if results.get(task, 0) > limit:
            failures.append(f"{task} took {results[task]:.4f}s (budget: {limit}s)")

    if failures:
        print("\nPERFORMANCE REGRESSION DETECTED:")
        for f in failures:
            print(f" - {f}")
        # Ideally exit with error code if strict, but for now just report
        # sys.exit(1)
    else:
        print("\nPerformance within budget.")


if __name__ == "__main__":
    run_regression_test()
